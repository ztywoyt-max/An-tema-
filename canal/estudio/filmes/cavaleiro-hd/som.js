// passos ao longo de um trecho
const passos = (t, dur, intervalo = 0.6, vol = 0.5) => ({ t, som: 'passosDescalco', dur, intervalo, vol });
const espada = (t, dur, longe = 0) => ({ t, som: 'arrastoEspada', dur, longe, intervalo: 0.9 });
// martelo na cerca: a pancada cai quando o braço chega embaixo (U.martelo((tl * 0.55) % 1))
const marteladas = (dur, desde = 0) => {
  const out = [];
  for (let t = 0.25 / 0.55; t < dur; t += 1 / 0.55) if (t > desde) out.push({ t: t + 0.02, som: 'pancada' });
  return out;
};
// prego riscando o capacete: o braço desce a cada volta de sin(tl * 2.2)
const riscos = (dur) => {
  const out = [];
  for (let t = (1.5 * Math.PI) / 2.2; t < dur - 0.6; t += (2 * Math.PI) / 2.2) out.push({ t, som: 'arrastoEspada', dur: 0.5, longe: 1 });
  return out;
};
// trovões: os clarões do cenário da tempestade caem em t ≈ 9.7·n e t ≈ 13.3·n − 4.1 (tempo do filme)
function trovoes(p) {
  const out = [];
  for (const [per, desl, atraso] of [[9.7, 0, 0.9], [13.3, -4.1, 1.6]]) {
    for (let n = Math.ceil((p.inicio - desl) / per); per * n + desl < p.fim; n++) {
      const t = per * n + desl - p.inicio + atraso;
      if (t >= 0 && t < p.fim - p.inicio) out.push({ t, som: 'trovao' });
    }
  }
  return out;
}

